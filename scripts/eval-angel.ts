const verbose = process.argv.includes("-v");
function run(name: string, set: [string, string][]) {
  let pass = 0;
  const misses: string[] = [];
  for (const [q, want] of set) {
    const got = parse(q, TODAY).intent as string;
    if (got === want) pass++;
    else misses.push(`  ✗ "${q}" → ${got} (want ${want})`);
  }
  if (verbose && misses.length) console.log(`${name} misses:\n${misses.join("\n")}`);
  console.log(`${name}: ${pass}/${set.length} understood correctly (${Math.round((pass / set.length) * 100)}%)`);
  return pass === set.length;
}
